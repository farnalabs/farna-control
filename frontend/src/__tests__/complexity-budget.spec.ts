/**
 * Complexity-budget ratchet for the frontend (frontend counterpart of the
 * backend's complexity gates).
 *
 * The gap
 * -------
 * `eslint.config.mjs` configures no `complexity`, `max-lines`,
 * `max-lines-per-function` or `max-depth` rule, so nothing stopped a view from
 * growing without bound: `views/PipelineEditorView.vue` reached 6,452 lines
 * (6,887 by this spec's whole-file count), `views/RunDetailView.vue` 2,659 and
 * `views/EvalEditorView.vue` 2,069. This spec is the stop.
 *
 * What it measures (per file, over `src/**`)
 * -----------------------------------------
 * - `lines` - every physical line in the file, template and `<style>` included.
 * - `maxFunctionComplexity` - McCabe complexity (`1 + decision points`) of the
 *   most complex function/method in the file's `<script>` blocks.
 *
 * The measuring instrument is `src/test-utils/complexity-measure.ts`: it locates
 * `<script>`/`<script setup>` blocks with `@vue/compiler-sfc`'s `parse()` and
 * walks them with the `typescript` compiler API. Both are existing dev
 * dependencies; nothing new is installed and eslint is never invoked. The
 * module docstring owns the exact list of counted decision points.
 *
 * Two gates
 * ---------
 * 1. Absolute ceilings for any file. Chosen from the measured distribution of
 *    the 383 product source files on 2026-11-27, so the gate starts as a ratchet
 *    on genuine outliers rather than a flood of exceptions:
 *      - 1200 lines. p50 138, p90 591, p95 803, p99 1460: 1200 is 1.5x p95 and
 *        above p99, i.e. beyond where normal files live, and still below the six
 *        pathologies that exist today (6887, 2877, 2228, 1460, 1325, 1225).
 *      - 25 complexity. p50 5, p90 12, p95 15, p99 19, max 30: 25 sits above
 *        p99 and grandfathers only the two files that genuinely exceed it
 *        (RunDetailView 30, router/index.ts 29).
 * 2. A checked-in budget (`frontend/complexity-budget.json`) pinning every file
 *    that ALREADY exceeds a ceiling, keyed by repo-relative path with its two
 *    measured values. A budgeted file may not grow past its entry. The budget
 *    only shrinks: an entry that no longer exceeds a ceiling is stale and must
 *    be deleted (that is the decomposition landing), and an entry for a file
 *    that no longer exists must be deleted too.
 *
 * A partial reduction (still above a ceiling, but smaller than budgeted) does
 * not fail: it warns, so a decomposition in flight is not blocked by a
 * bookkeeping edit. The final step of that decomposition drops the entry below
 * its ceilings and then the stale-entry failure forces its deletion.
 *
 * Regenerating the budget
 * -----------------------
 * The writer is the only supported way to change the budget. After a sweep, run
 *
 *     cd frontend
 *     COMPLEXITY_BUDGET_WRITE=1 pnpm exec vitest run src/__tests__/complexity-budget.spec.ts
 *
 * which rewrites the file from the current tree (ceiling-breakers only, sorted).
 * Run it twice on the same tree: the second run writes no diff.
 *
 * Scope
 * -----
 * Product source only, by construction, and each exclusion is asserted below:
 * - tests (`src/__tests__/**`, `*.spec.ts`, `*.test.ts`) - a 4,000-line spec is a
 *   test-double library, not a shipped surface, and gating it would fail every
 *   ordinary PR that adds a case;
 * - `src/test-utils/**` - test scaffolding, including the measuring instrument;
 * - `src/lib/api/schema.ts` - generated by openapi-typescript (its banner is
 *   asserted below, so a hand-authored file cannot claim the exclusion).
 */
import { describe, it, expect } from 'vitest'
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, relative, extname, sep, resolve } from 'node:path'
import { countLines, measureSource, type FileMeasurement } from '../test-utils/complexity-measure'

const SRC_DIR = join(__dirname, '..')
const FRONTEND_ROOT = resolve(SRC_DIR, '..')
const REPO_ROOT = resolve(FRONTEND_ROOT, '..')
const BUDGET_PATH = join(FRONTEND_ROOT, 'complexity-budget.json')
const BUDGET_NAME = 'frontend/complexity-budget.json'

/** A budgeted file may not exceed either ceiling, and no unbudgeted file may. */
const ABSOLUTE_MAX_LINES = 1200
const ABSOLUTE_MAX_FUNCTION_COMPLEXITY = 25

/** Directories (relative to `src/`) that are test scaffolding, not product source. */
const EXCLUDED_DIRS = ['__tests__', 'test-utils']
/** Test-file suffixes anywhere under `src/`. */
const TEST_SUFFIXES = ['.spec.ts', '.test.ts']
/** Generated files (relative to `src/`), each proved generated by its banner. */
const GENERATED_FILES = new Set(['lib/api/schema.ts'])
const GENERATED_MARKER = 'This file was auto-generated by openapi-typescript.'

/**
 * The scan parses every product source file through the TypeScript compiler.
 * That is a few seconds on an idle machine and tens of seconds on a loaded or
 * cold one, far above the suite's 15s default, so the assertions that trigger
 * it opt out instead of racing a timeout that measures the machine, not the
 * code.
 */
const SCAN_TIMEOUT_MS = 180_000

/** The two numbers pinned per file. */
export interface BudgetEntry {
  lines: number
  maxFunctionComplexity: number
}

export type Budget = Record<string, BudgetEntry>

function walk(dir: string): string[] {
  const files: string[] = []
  // `withFileTypes` avoids a stat() per entry; this tree is walked on a cold
  // filesystem in CI and every syscall here is paid three times otherwise.
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...walk(full))
    } else if (['.vue', '.ts'].includes(extname(entry.name))) {
      const rel = relative(SRC_DIR, full).split(sep).join('/')
      if (TEST_SUFFIXES.some((suffix) => rel.endsWith(suffix))) continue
      if (GENERATED_FILES.has(rel)) continue
      files.push(full)
    }
  }
  return files
}

/** The product source files the gate polices. Walked once per run. */
let cachedFiles: string[] | null = null
function scannedFiles(): string[] {
  if (cachedFiles) return cachedFiles
  cachedFiles = walk(SRC_DIR)
    .filter((path) => {
      const rel = relative(SRC_DIR, path).split(sep).join('/')
      return !EXCLUDED_DIRS.some((dir) => rel === dir || rel.startsWith(`${dir}/`))
    })
    .sort()
  return cachedFiles
}

/** Repo-relative path, the budget's key. */
function repoRelative(path: string): string {
  return relative(REPO_ROOT, path).split(sep).join('/')
}

interface ScanResult {
  measurements: Map<string, FileMeasurement>
  /** Scanned files whose own text carries the generator banner (there must be none). */
  generatedMarker: string[]
}

/** Measure every scanned file once; the whole spec shares the result. */
let cachedScan: ScanResult | null = null
function scan(): ScanResult {
  if (cachedScan) return cachedScan
  const measurements = new Map<string, FileMeasurement>()
  const generatedMarker: string[] = []
  for (const path of scannedFiles()) {
    const source = readFileSync(path, 'utf-8')
    const key = repoRelative(path)
    measurements.set(key, measureSource(source, path))
    if (source.includes(GENERATED_MARKER)) generatedMarker.push(key)
  }
  cachedScan = { measurements, generatedMarker }
  return cachedScan
}

/** Budget entries for the files that currently exceed a ceiling, sorted by path. */
function collectBudget(measurements: Map<string, FileMeasurement>): Budget {
  const budget: Budget = {}
  for (const [path, measurement] of measurements) {
    if (!exceedsCeiling(measurement)) continue
    budget[path] = { lines: measurement.lines, maxFunctionComplexity: measurement.maxFunctionComplexity }
  }
  return Object.fromEntries(Object.entries(budget).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
}

function exceedsCeiling(measurement: FileMeasurement): boolean {
  return (
    measurement.lines > ABSOLUTE_MAX_LINES ||
    measurement.maxFunctionComplexity > ABSOLUTE_MAX_FUNCTION_COMPLEXITY
  )
}

/** Validate a parsed budget, rejecting anything the ratchet could not enforce. */
function parseBudget(raw: unknown): Budget {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new Error(`${BUDGET_NAME} must be a JSON object keyed by repo-relative path`)
  }
  const budget: Budget = {}
  for (const [path, entry] of Object.entries(raw as Record<string, unknown>)) {
    if (!path.startsWith('frontend/src/')) {
      throw new Error(`${BUDGET_NAME} entry '${path}' must be a repo-relative path under frontend/src/`)
    }
    if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) {
      throw new Error(`${BUDGET_NAME} entry '${path}' must be { lines, maxFunctionComplexity }`)
    }
    const record = entry as Record<string, unknown>
    const unknownKeys = Object.keys(record).filter((key) => key !== 'lines' && key !== 'maxFunctionComplexity')
    if (unknownKeys.length > 0) {
      throw new Error(`${BUDGET_NAME} entry '${path}' has unknown key(s): ${unknownKeys.join(', ')}`)
    }
    for (const key of ['lines', 'maxFunctionComplexity'] as const) {
      const value = record[key]
      if (typeof value !== 'number' || !Number.isInteger(value) || value < 1) {
        throw new Error(`${BUDGET_NAME} entry '${path}'.${key} must be a positive integer, got ${String(value)}`)
      }
    }
    budget[path] = { lines: record.lines as number, maxFunctionComplexity: record.maxFunctionComplexity as number }
  }
  return budget
}

function loadBudget(): Budget {
  // Editors on Windows happily save JSON with a UTF-8 BOM; JSON.parse rejects
  // it with an unhelpful "Unexpected token", so strip it here.
  const text = readFileSync(BUDGET_PATH, 'utf-8').replace(/^\uFEFF/, '')
  return parseBudget(JSON.parse(text))
}

interface RatchetResult {
  /** Over budget, or over a ceiling with no budget entry. Must fail. */
  regressions: string[]
  /** Budget entries that must be deleted (file gone, or no longer over a ceiling). Must fail. */
  stale: string[]
  /** Budget entries larger than today's measurement while still over a ceiling. Warn only. */
  reductions: string[]
}

/**
 * Compare measurements against the budget.
 *
 * - a budgeted file above either budgeted value is a regression;
 * - an unbudgeted file above either ceiling is a regression (a NEW offender);
 * - a budget entry whose file is gone, or whose file no longer exceeds a
 *   ceiling, is stale: the ratchet only shrinks, so it must be deleted;
 * - a budget entry above today's measurement (while still over a ceiling) is a
 *   reduction: it warns so it stays visible, but does not fail.
 */
function evaluateBudget(budget: Budget, measurements: Map<string, FileMeasurement>): RatchetResult {
  const regressions: string[] = []
  const stale: string[] = []
  const reductions: string[] = []

  for (const [path, measurement] of measurements) {
    const entry = budget[path]
    if (!entry) {
      if (measurement.lines > ABSOLUTE_MAX_LINES) {
        regressions.push(`${path}: ${measurement.lines} lines > ${ABSOLUTE_MAX_LINES} ceiling (new offender)`)
      }
      if (measurement.maxFunctionComplexity > ABSOLUTE_MAX_FUNCTION_COMPLEXITY) {
        regressions.push(
          `${path}: maxFunctionComplexity ${measurement.maxFunctionComplexity} > ${ABSOLUTE_MAX_FUNCTION_COMPLEXITY} ceiling (new offender)`,
        )
      }
      continue
    }
    if (measurement.lines > entry.lines) {
      regressions.push(`${path}: ${measurement.lines} lines > budget ${entry.lines} (grew)`)
    }
    if (measurement.maxFunctionComplexity > entry.maxFunctionComplexity) {
      regressions.push(
        `${path}: maxFunctionComplexity ${measurement.maxFunctionComplexity} > budget ${entry.maxFunctionComplexity} (grew)`,
      )
    }
  }

  for (const [path, entry] of Object.entries(budget)) {
    const measurement = measurements.get(path)
    if (!measurement) {
      stale.push(`${path}: budget entry for a file that no longer exists (delete it)`)
      continue
    }
    if (!exceedsCeiling(measurement)) {
      stale.push(
        `${path}: no longer exceeds a ceiling (${measurement.lines} lines, complexity ${measurement.maxFunctionComplexity}) - delete the entry`,
      )
      continue
    }
    if (measurement.lines < entry.lines) {
      reductions.push(`${path}: ${entry.lines} -> ${measurement.lines} lines (lower the entry)`)
    }
    if (measurement.maxFunctionComplexity < entry.maxFunctionComplexity) {
      reductions.push(
        `${path}: complexity ${entry.maxFunctionComplexity} -> ${measurement.maxFunctionComplexity} (lower the entry)`,
      )
    }
  }

  return { regressions, stale, reductions }
}

function lines(values: string[]): string {
  return values.map((value) => `  ${value}`).join('\n')
}

// Regeneration path: the gate and the writer share `scan()` and
// `collectBudget()`, so the checked-in budget cannot be produced by a different
// scanner from the one that enforces it.
if (process.env.COMPLEXITY_BUDGET_WRITE === '1') {
  writeFileSync(BUDGET_PATH, `${JSON.stringify(collectBudget(scan().measurements), null, 2)}\n`)
}

describe('complexity-budget ratchet', () => {
  it('counts every decision point the metric is defined to count', () => {
    const source = `
function sample(a: number, b: any, c: any) {
  if (a > 1) { a = 0 }
  for (let i = 0; i < a; i += 1) { a += i }
  for (const key in b) { a += 1 }
  for (const value of b) { a += 1 }
  while (a > 10) { a -= 1 }
  do { a += 1 } while (a < 0)
  switch (a) {
    case 1: break
    case 2: break
    default: break
  }
  try { a += 1 } catch { a -= 1 }
  const ternary = a > 0 ? 1 : 2
  const and = a > 0 && b
  const or = a > 0 || b
  const nullish = c ?? 0
  const chained = c?.d?.[a]?.(1)
  a &&= 1
  return [ternary, and, or, nullish, chained]
}
`
    const measurement = measureSource(source, 'Sample.ts')
    // if 1, for 1, for-in 1, for-of 1, while 1, do 1, case 2, catch 1,
    // ternary 1, && 1, || 1, ?? 1, ?. x3, &&= 1 = 17 decision points.
    expect(measurement.maxFunctionComplexity).toBe(18)
    expect(measurement.worstFunction).toMatchObject({ name: 'sample', decisions: 17, complexity: 18 })

    // A function with no branches is complexity 1; a file with no function is 0.
    expect(measureSource('const f = () => 1', 'Trivial.ts').maxFunctionComplexity).toBe(1)
    expect(measureSource('export const x = 1\nexport type Y = string', 'NoFunctions.ts').maxFunctionComplexity).toBe(0)
  })

  it('measures each nested function on its own, never charging a closure to its host', () => {
    const source = `
function outer(flag: boolean) {
  if (flag) { return 0 }
  const inner = (a: number) => {
    if (a > 1) return 1
    if (a > 2) return 2
    return a > 3 ? 3 : 4
  }
  return inner(1)
}
`
    const measurement = measureSource(source, 'Nested.ts')
    // outer: one `if` -> 2. inner: two ifs + ternary -> 4. The file maximum is
    // the inner function, and outer is NOT inflated by it.
    expect(measurement.functionCount).toBe(2)
    expect(measurement.maxFunctionComplexity).toBe(4)
    expect(measurement.worstFunction).toMatchObject({ name: 'inner', complexity: 4 })
  })

  it('measures the script blocks of a .vue file and ignores template complexity', () => {
    const source = `<template>
  <div>
    <p v-if="a && b">one</p>
    <p v-else-if="c || d">two</p>
    <p v-else>three</p>
    <span v-for="item in items" :key="item.id">{{ item?.label ?? '-' }}</span>
  </div>
</template>

<script setup lang="ts">
const pick = (flag: boolean) => (flag ? 'a' : 'b')
</script>
`
    const measurement = measureSource(source, 'Sample.vue')
    // Only the script's ternary is a decision point: the template's v-if/v-for/
    // optional chaining are the template compiler's AST, out of scope by design.
    expect(measurement.maxFunctionComplexity).toBe(2)
    expect(measurement.worstFunction).toMatchObject({ name: 'pick', complexity: 2 })
    // And the file's line count covers the template and script blocks.
    expect(measurement.lines).toBe(countLines(source))
  })

  it('reads both <script> and <script setup>, reporting the real file line', () => {
    const source = `<template><div /></template>
<script lang="ts">
export default { name: 'Sample' }
</script>
<script setup lang="ts">
const onClick = () => {
  if (!window) return
  if (document.hidden) return
}
</script>
`
    const measurement = measureSource(source, 'Sample.vue')
    expect(measurement.functionCount).toBe(1)
    expect(measurement.worstFunction).toMatchObject({ name: 'onClick', complexity: 3 })
    // `const onClick` is on line 6 of the file; the block's offset is applied.
    expect(measurement.worstFunction?.line).toBe(6)
  })

  it('counts lines the way the ceiling means them', () => {
    expect(countLines('')).toBe(0)
    expect(countLines('one')).toBe(1)
    expect(countLines('one\n')).toBe(1)
    expect(countLines('one\ntwo')).toBe(2)
    expect(countLines('one\r\ntwo\r\n')).toBe(2)
  })

  it('fails a file that grows past its budget', () => {
    const budget: Budget = { 'frontend/src/Grown.vue': { lines: 7000, maxFunctionComplexity: 20 } }
    const measurements = new Map<string, FileMeasurement>([
      ['frontend/src/Grown.vue', { lines: 7001, maxFunctionComplexity: 21, worstFunction: null, functionCount: 1 }],
    ])

    const result = evaluateBudget(budget, measurements)
    expect(result.regressions.join('\n')).toContain('frontend/src/Grown.vue: 7001 lines > budget 7000 (grew)')
    expect(result.regressions.join('\n')).toContain(
      'frontend/src/Grown.vue: maxFunctionComplexity 21 > budget 20 (grew)',
    )
    expect(result.stale).toEqual([])
  })

  it('fails a new file that exceeds either absolute ceiling', () => {
    const measurements = new Map<string, FileMeasurement>([
      ['frontend/src/Long.vue', { lines: ABSOLUTE_MAX_LINES + 1, maxFunctionComplexity: 3, worstFunction: null, functionCount: 1 }],
      ['frontend/src/Tangled.ts', { lines: 10, maxFunctionComplexity: ABSOLUTE_MAX_FUNCTION_COMPLEXITY + 1, worstFunction: null, functionCount: 1 }],
    ])

    const result = evaluateBudget({}, measurements)
    expect(result.regressions.join('\n')).toContain('frontend/src/Long.vue: 1201 lines > 1200 ceiling (new offender)')
    expect(result.regressions.join('\n')).toContain(
      'frontend/src/Tangled.ts: maxFunctionComplexity 26 > 25 ceiling (new offender)',
    )
  })

  it('passes a new file exactly at the ceilings, so only the boundary is policed', () => {
    const measurements = new Map<string, FileMeasurement>([
      [
        'frontend/src/AtCeiling.vue',
        { lines: ABSOLUTE_MAX_LINES, maxFunctionComplexity: ABSOLUTE_MAX_FUNCTION_COMPLEXITY, worstFunction: null, functionCount: 1 },
      ],
    ])
    expect(evaluateBudget({}, measurements).regressions).toEqual([])
  })

  it('fails a budget entry whose file is gone', () => {
    const budget: Budget = { 'frontend/src/Deleted.vue': { lines: 7000, maxFunctionComplexity: 20 } }
    const result = evaluateBudget(budget, new Map())
    expect(result.stale).toHaveLength(1)
    expect(result.stale[0]).toContain('frontend/src/Deleted.vue: budget entry for a file that no longer exists')
  })

  it('fails a budget entry that no longer exceeds a ceiling', () => {
    const budget: Budget = { 'frontend/src/Shrunk.vue': { lines: 7000, maxFunctionComplexity: 20 } }
    const measurements = new Map<string, FileMeasurement>([
      ['frontend/src/Shrunk.vue', { lines: 300, maxFunctionComplexity: 9, worstFunction: null, functionCount: 3 }],
    ])
    const result = evaluateBudget(budget, measurements)
    expect(result.stale).toHaveLength(1)
    expect(result.stale[0]).toContain('no longer exceeds a ceiling')
    expect(result.regressions).toEqual([])
  })

  it('warns, but does not fail, on a reduction that is still over a ceiling', () => {
    const budget: Budget = { 'frontend/src/Swept.vue': { lines: 7000, maxFunctionComplexity: 28 } }
    const measurements = new Map<string, FileMeasurement>([
      ['frontend/src/Swept.vue', { lines: 2000, maxFunctionComplexity: 26, worstFunction: null, functionCount: 40 }],
    ])
    const result = evaluateBudget(budget, measurements)
    expect(result.regressions).toEqual([])
    expect(result.stale).toEqual([])
    expect(result.reductions.join('\n')).toContain('frontend/src/Swept.vue: 7000 -> 2000 lines')
    expect(result.reductions.join('\n')).toContain('frontend/src/Swept.vue: complexity 28 -> 26')
  })

  it('rejects a budget entry that is not a positive integer', () => {
    expect(() => parseBudget({ 'frontend/src/X.vue': { lines: 0, maxFunctionComplexity: 3 } })).toThrow(
      /positive integer/,
    )
    expect(() => parseBudget({ 'frontend/src/X.vue': { lines: 10, maxFunctionComplexity: 1.5 } })).toThrow(
      /positive integer/,
    )
  })

  it('rejects a budget entry with unknown keys, a non-object, or a foreign path', () => {
    expect(() =>
      parseBudget({ 'frontend/src/X.vue': { lines: 10, maxFunctionComplexity: 1, depth: 4 } }),
    ).toThrow(/unknown key/)
    expect(() => parseBudget({ 'frontend/src/X.vue': 10 })).toThrow(/must be \{ lines, maxFunctionComplexity \}/)
    expect(() => parseBudget({ 'backend/src/x.py': { lines: 10, maxFunctionComplexity: 1 } })).toThrow(
      /repo-relative path/,
    )
  })

  it('scans the product source files it is meant to police', () => {
    const files = scannedFiles()
    // A broken walk would make every assertion below pass vacuously.
    expect(files.length).toBeGreaterThan(300)
    // ...and it really reaches the files the gap is about.
    const pipelineEditor = files.find((path) => path.endsWith(join('views', 'PipelineEditorView.vue')))
    expect(pipelineEditor, 'the scan must reach views/PipelineEditorView.vue').toBeTruthy()
    expect(scan().measurements.get(repoRelative(pipelineEditor!))!.lines).toBeGreaterThan(ABSOLUTE_MAX_LINES)
  }, SCAN_TIMEOUT_MS)

  it('never scans a spec, the test scaffolding, or the generated API schema', () => {
    const scanned = scannedFiles()
    expect(scanned.some((path) => path.includes(`${sep}__tests__${sep}`))).toBe(false)
    expect(scanned.some((path) => path.includes(`${sep}test-utils${sep}`))).toBe(false)
    expect(scanned.some((path) => path.endsWith('.spec.ts') || path.endsWith('.test.ts'))).toBe(false)
    // The fixtures exist and are large - they are excluded by construction, not
    // by accident of being small.
    const bigSpec = join(SRC_DIR, '__tests__', 'PipelineEditorView.spec.ts')
    expect(existsSync(bigSpec)).toBe(true)
    expect(countLines(readFileSync(bigSpec, 'utf-8'))).toBeGreaterThan(ABSOLUTE_MAX_LINES)
    const generated = join(SRC_DIR, 'lib', 'api', 'schema.ts')
    expect(scanned).not.toContain(generated)
  })

  it('every generated-file exclusion is a real generated file, and nothing else claims to be', () => {
    for (const rel of GENERATED_FILES) {
      const source = readFileSync(join(SRC_DIR, rel), 'utf-8')
      expect(source, `${rel} must carry the generator banner it is excluded for`).toContain(GENERATED_MARKER)
    }
    // The converse: a scanned file carrying the banner is a generated file that
    // is either hand-authored (it must not be) or missing from GENERATED_FILES.
    expect(
      scan().generatedMarker,
      'A generated file is being scanned as product source. Add it to GENERATED_FILES, or remove the banner:',
    ).toEqual([])
  }, SCAN_TIMEOUT_MS)

  it('never exceeds the checked-in budget, and has no stale entries', () => {
    const { regressions, stale, reductions } = evaluateBudget(loadBudget(), scan().measurements)

    for (const line of reductions) {
      console.warn(
        `Complexity budget can shrink further (not a failure): lower or remove this entry in ${BUDGET_NAME}:\n  ${line}`,
      )
    }

    const grewTitle = `A file is above its complexity budget. Decompose it (extract components/composables) rather than raising the budget in ${BUDGET_NAME}, which may only be lowered or deleted. A file with no budget entry must stay at or below ${ABSOLUTE_MAX_LINES} lines and complexity ${ABSOLUTE_MAX_FUNCTION_COMPLEXITY}:`
    const staleTitle = `The complexity budget in ${BUDGET_NAME} has stale entries. The ratchet only shrinks, so delete every entry below (the file is gone, or it no longer exceeds a ceiling, so its allowance is not needed):`
    expect(regressions, `${grewTitle}\n${lines(regressions)}`).toEqual([])
    expect(stale, `${staleTitle}\n${lines(stale)}`).toEqual([])
  }, SCAN_TIMEOUT_MS)
})
